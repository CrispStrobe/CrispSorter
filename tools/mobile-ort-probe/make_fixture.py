#!/usr/bin/env python3
"""Generate the self-authored, weight-free ONNX Add graph used by the target probe.

The encoded fields are the public ONNX protobuf schema: ModelProto (IR 8,
opset 13), GraphProto, NodeProto, ValueInfoProto and tensor shapes. This script
does not fetch models or execute inference. Regeneration must be byte-exact.
"""
from __future__ import annotations

import hashlib
from pathlib import Path


def varint(value):
    output = bytearray()
    while value >= 128:
        output.append((value & 127) | 128)
        value >>= 7
    return bytes(output + bytes([value]))


def integer(field, value):
    return varint(field << 3) + varint(value)


def message(field, value):
    if isinstance(value, str):
        value = value.encode("utf-8")
    return varint((field << 3) | 2) + varint(len(value)) + value


def value_info(name):
    shape = message(1, integer(1, 2)) + message(1, integer(1, 2))
    tensor_type = integer(1, 1) + message(2, shape)  # FLOAT [2, 2]
    return message(1, name) + message(2, message(1, tensor_type))


def model():
    node = message(1, "A") + message(1, "B") + message(2, "Y") + message(3, "sum") + message(4, "Add")
    graph = message(1, node) + message(2, "CrispSorter mobile runtime probe")
    graph += message(11, value_info("A")) + message(11, value_info("B")) + message(12, value_info("Y"))
    return integer(1, 8) + message(2, "CrispSorter") + message(7, graph) + message(8, integer(2, 13))


def generated_header():
    data = model()
    rows = ["    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start + 12]) + "," for start in range(0, len(data), 12)]
    return ("// Self-authored weight-free ONNX Add graph. Generated by make_fixture.py.\n"
            f"// SHA-256: {hashlib.sha256(data).hexdigest()}\n"
            "static const unsigned char ADD_MODEL[] = {\n" + "\n".join(rows) + "\n};\n")


if __name__ == "__main__":
    root = Path(__file__).resolve().parent
    (root / "add_model.h").write_text(generated_header())
    print(hashlib.sha256(model()).hexdigest())
