#!/usr/bin/env python3
"""Execute a source-paired Linux desktop binary and observe real GUI startup.

Run only on a dedicated hosted Xvfb/DBus session after the production frontend
and application have been built. No models, fixtures, app hooks or mocked IPC
are installed. A passing receipt qualifies binary linkage and observed startup;
it does not qualify desktop OCR interactions or the screenshot's visual content.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
import json
import os
from pathlib import Path
import platform
import re
import signal
import struct
import subprocess
import sys
import tempfile
import threading
import time
import tomllib
from urllib.parse import unquote, urlsplit


FATAL = re.compile(
    r"panicked at|error while loading shared libraries|undefined symbol:|"
    r"cannot open display|failed to initialize gtk|WebKitWebProcess.*(?:crash|terminated)",
    re.IGNORECASE,
)


def sha256(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def file_identity(path):
    return {"path": str(path), "bytes": path.stat().st_size, "sha256": sha256(path)}


def command(argv, *, env=None, timeout=30):
    result = subprocess.run(argv, capture_output=True, text=True, env=env, timeout=timeout)
    return {"argv": [str(arg) for arg in argv], "returncode": result.returncode,
            "stdout": result.stdout, "stderr": result.stderr}


def require_success(result):
    if result["returncode"] != 0:
        raise ValueError("Command failed: " + " ".join(result["argv"]) + "\n" + result["stderr"][-4000:])
    return result["stdout"].strip()


def source_identity(source):
    commit = require_success(command(["git", "-C", str(source), "rev-parse", "HEAD"]))
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError("Source checkout has no immutable commit identity")
    changed = require_success(command(["git", "-C", str(source), "diff", "--name-only", "HEAD"]))
    # npm prebuild creates a timestamped license inventory. Its generated bytes
    # are included in the frontend manifest; application sources must be clean.
    if set(changed.splitlines()) - {"static/licenses.json"}:
        raise ValueError("Application or native source changed after checkout: " + changed)
    return {"commit": commit, "tracked_generated_changes": changed.splitlines()}


def validate_linker_output(output, native_library):
    if re.search(r"not found|undefined symbol", output, re.IGNORECASE):
        raise ValueError("Unresolved dynamic library or symbol")
    paths = re.findall(r"^\s*libcrispembed\S*\s+=>\s+(\S+)\s+\(", output, re.MULTILINE)
    if len(paths) != 1 or Path(paths[0]).resolve() != native_library.resolve():
        raise ValueError("Executable does not resolve exactly the paired CrispEmbed library")
    return paths[0]


def validate_mapping(maps, native_library):
    paths = set()
    for line in maps.splitlines():
        fields = line.split(maxsplit=5)
        if len(fields) == 6 and "libcrispembed" in Path(fields[5]).name:
            if fields[5].endswith(" (deleted)"):
                raise ValueError("Mapped native library was deleted")
            paths.add(str(Path(fields[5]).resolve()))
    if paths != {str(native_library.resolve())}:
        raise ValueError("Running process does not map exactly the paired CrispEmbed library")
    return sorted(paths)


def validate_cli(results, expected_version):
    help_text = require_success(results["help"])
    if "Usage:" not in help_text or not re.search(r"(?m)^\s+ocr\s", help_text):
        raise ValueError("Actual executable help is missing the OCR command")
    if require_success(results["version_flag"]) != "crispsorter " + expected_version:
        raise ValueError("Executable --version differs from the source manifest")
    version = json.loads(require_success(results["version_json"]))
    if version != {"name": "crispsorter", "version": expected_version,
                   "target": "linux", "arch": platform.machine()}:
        raise ValueError("Executable version JSON differs from the source/target")
    rejected = results["invalid_argument"]
    if rejected["returncode"] != 2 or "unexpected argument" not in rejected["stderr"]:
        raise ValueError("Invalid CLI argument did not fail before GUI startup")
    for result in results.values():
        if FATAL.search(result["stdout"] + result["stderr"]):
            raise ValueError("Fatal error in executable CLI startup")
    return version


def frontend_evidence(requests):
    successful = {urlsplit(item["path"]).path for item in requests
                  if item["method"] == "GET" and item["status"] == 200}
    entry_scripts = sorted(path for path in successful
                           if re.fullmatch(r"/_app/immutable/entry/(?:start|app)\.[^/]+\.js", path))
    entry_types = {Path(path).name.split(".")[0] for path in entry_scripts}
    if not ({"/", "/index.html"} & successful) or entry_types != {"start", "app"}:
        raise ValueError("Production HTML and both application entry scripts were not served")
    return entry_scripts


def png_dimensions(data):
    if len(data) < 33 or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        raise ValueError("Window capture is not a PNG")
    width, height = struct.unpack_from(">II", data, 16)
    if not 320 <= width <= 4096 or not 240 <= height <= 4096:
        raise ValueError("Window capture has implausible dimensions")
    return {"width": width, "height": height}


def process_sample(pid, started):
    status = Path(f"/proc/{pid}/status").read_text()
    values = {key: int(value) for key, value in
              re.findall(r"^(VmRSS|VmHWM|VmSize|VmPeak):\s+(\d+)\s+kB$", status, re.MULTILINE)}
    if "VmRSS" not in values or "VmHWM" not in values:
        raise ValueError("Running application has no readable memory observation")
    smaps = Path(f"/proc/{pid}/smaps_rollup").read_text()
    match = re.search(r"^Pss:\s+(\d+)\s+kB$", smaps, re.MULTILINE)
    if match:
        values["Pss"] = int(match.group(1))
    return {"elapsed_ms": round((time.monotonic() - started) * 1000),
            "pid": pid, "memory_kib": values}


def descendant_processes(pid):
    rows = require_success(command(["ps", "-eo", "pid=,ppid=,comm="])).splitlines()
    parsed = [row.split(maxsplit=2) for row in rows]
    known = {pid}
    selected = []
    while True:
        children = [row for row in parsed if len(row) == 3 and int(row[1]) in known and int(row[0]) not in known]
        if not children:
            return selected
        for child, parent, name in children:
            known.add(int(child))
            selected.append({"pid": int(child), "ppid": int(parent), "name": name})


def find_window(pid, env):
    query = command(["xdotool", "search", "--onlyvisible", "--pid", str(pid)], env=env, timeout=5)
    if query["returncode"] not in (0, 1):
        require_success(query)
    candidates = []
    for window in query["stdout"].split():
        if not window.isdigit():
            raise ValueError("Window query returned an invalid identifier")
        owner = require_success(command(["xdotool", "getwindowpid", window], env=env))
        name = require_success(command(["xdotool", "getwindowname", window], env=env))
        if owner == str(pid) and name == "CrispSorter":
            candidates.append({"id": window, "pid": int(owner), "title": name})
    if len(candidates) > 1:
        raise ValueError("More than one visible application window matched")
    return candidates[0] if candidates else None


def frontend_manifest(frontend):
    files = []
    for item in sorted(frontend.rglob("*")):
        if item.is_symlink():
            raise ValueError("Production frontend contains a symbolic link")
        if item.is_file():
            files.append({**file_identity(item), "path": item.relative_to(frontend).as_posix()})
    if not any(item["path"] == "index.html" for item in files):
        raise ValueError("Production frontend index.html is missing")
    if len(files) > 100_000 or sum(item["bytes"] for item in files) > 2 * 1024**3:
        raise ValueError("Production frontend exceeds the qualification size bound")
    return files


def serve_frontend(frontend, requests):
    class Handler(SimpleHTTPRequestHandler):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, directory=str(frontend), **kwargs)

        def log_request(self, code="-", size="-"):
            requests.append({"method": self.command, "path": self.path, "status": int(code)})

        def log_message(self, *_args):
            pass

        def do_GET(self):
            # This server has one role: serve the recorded static build. It has
            # no proxy, arbitrary file read, navigation fallback or test hooks.
            path = unquote(urlsplit(self.path).path)
            if ".." in Path(path).parts or "\x00" in path:
                self.send_error(400)
                return
            super().do_GET()

    server = ThreadingHTTPServer(("127.0.0.1", 1420), Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server, thread


def execute(args, output, receipt):
    source, native_source = args.source.resolve(), args.native_source.resolve()
    binary, native_library, frontend = args.binary.resolve(), args.native_library.resolve(), args.frontend.resolve()
    if platform.system() != "Linux" or not os.environ.get("DISPLAY") or not os.environ.get("DBUS_SESSION_BUS_ADDRESS"):
        raise ValueError("A dedicated Linux Xvfb and DBus session is required")
    if not binary.is_file() or not os.access(binary, os.X_OK) or not native_library.is_file():
        raise ValueError("Built executable and paired shared library are required")
    receipt.update({"source": source_identity(source), "native_source": source_identity(native_source),
                    "binary": file_identity(binary), "native_library": file_identity(native_library),
                    "features": ["desktop", "ocr-workspace"], "default_features": False,
                    "system": {"platform": platform.platform(), "machine": platform.machine()}})
    expected_native = os.environ.get("OCR_CRISPEMBED_REF")
    if not expected_native or receipt["native_source"]["commit"] != expected_native:
        raise ValueError("Native checkout differs from the workflow's immutable source pin")
    version = tomllib.loads((source / "src-tauri/Cargo.toml").read_text())["package"]["version"]
    config = json.loads((source / "src-tauri/tauri.conf.json").read_text())
    if config["build"]["devUrl"] != "http://localhost:1420":
        raise ValueError("Debug app frontend URL changed; review the startup server")
    files = frontend_manifest(frontend)
    (output / "frontend-files.json").write_text(json.dumps(files, indent=2) + "\n")
    receipt["frontend"] = {"manifest": file_identity(output / "frontend-files.json"), "files": len(files),
                           "bytes": sum(item["bytes"] for item in files), "kind": "production-static-build"}
    env = dict(os.environ, LD_BIND_NOW="1", GDK_BACKEND="x11", GSETTINGS_BACKEND="memory",
               LIBGL_ALWAYS_SOFTWARE="1", WEBKIT_DISABLE_DMABUF_RENDERER="1")
    linker = command(["ldd", "-r", str(binary)], env=env, timeout=60)
    (output / "linker.json").write_text(json.dumps(linker, indent=2) + "\n")
    require_success(linker)
    receipt["resolved_native_library"] = validate_linker_output(linker["stdout"] + linker["stderr"], native_library)
    cli_env = {key: value for key, value in env.items() if key not in ("DISPLAY", "WAYLAND_DISPLAY")}
    receipt["cli"] = {}
    for name, argv in (("help", ["--help"]), ("version_flag", ["--version"]),
                       ("version_json", ["version"]), ("invalid_argument", ["version", "--definitely-not-supported"])):
        receipt["cli"][name] = command([str(binary), *argv], env=cli_env)
    receipt["reported_version"] = validate_cli(receipt["cli"], version)
    receipt["cli_passed"] = True

    requests, samples = [], []
    receipt.update({"requests": requests, "memory_samples": samples})
    server = thread = process = None
    with tempfile.TemporaryDirectory(prefix="crispsorter-desktop-startup-") as state:
        # Isolate only standard app directories. HOME is never repurposed.
        for key, directory in (("XDG_DATA_HOME", "data"), ("XDG_CONFIG_HOME", "config"),
                               ("XDG_CACHE_HOME", "cache"), ("XDG_RUNTIME_DIR", "runtime")):
            path = Path(state) / directory
            path.mkdir(mode=0o700)
            env[key] = str(path)
        try:
            server, thread = serve_frontend(frontend, requests)
            with (output / "application.log").open("w") as log:
                started = time.monotonic()
                process = subprocess.Popen([str(binary)], cwd=source, env=env, stdout=log,
                                           stderr=subprocess.STDOUT, start_new_session=True)
                receipt["pid"] = process.pid
                deadline, ready_at, window = started + args.timeout_seconds, None, None
                while time.monotonic() < deadline:
                    if process.poll() is not None:
                        raise ValueError(f"Application exited during startup: {process.returncode}")
                    if not samples or time.monotonic() - started >= samples[-1]["elapsed_ms"] / 1000 + 1:
                        samples.append(process_sample(process.pid, started))
                    log_text = (output / "application.log").read_text()
                    if FATAL.search(log_text):
                        raise ValueError("Application emitted a fatal startup error")
                    window = find_window(process.pid, env)
                    try:
                        scripts = frontend_evidence(requests)
                    except ValueError:
                        scripts = None
                    if window and scripts and f"CrispSorter v{version} starting" in log_text:
                        ready_at = ready_at or time.monotonic()
                        if time.monotonic() - ready_at >= args.observe_seconds:
                            break
                    else:
                        ready_at = None
                    time.sleep(0.25)
                else:
                    raise ValueError("Real application window/frontend did not remain ready within the bounded timeout")

                running_binary = Path(f"/proc/{process.pid}/exe").resolve()
                if running_binary != binary or sha256(running_binary) != receipt["binary"]["sha256"]:
                    raise ValueError("Observed process differs from the built executable")
                maps = Path(f"/proc/{process.pid}/maps").read_text()
                receipt["mapped_native_libraries"] = validate_mapping(maps, native_library)
                if sha256(native_library) != receipt["native_library"]["sha256"]:
                    raise ValueError("Native library changed during application startup")
                (output / "application-maps.txt").write_text(maps)
                receipt["descendants"] = descendant_processes(process.pid)
                receipt["window"] = window
                receipt["frontend"]["served_entry_scripts"] = scripts
                screenshot = output / "desktop-startup.png"
                require_success(command(["import", "-window", window["id"], str(screenshot)], env=env))
                receipt["screenshot"] = {**file_identity(screenshot), **png_dimensions(screenshot.read_bytes()),
                                         "visual_review": "pending"}
                if process.poll() is not None:
                    raise ValueError("Application exited while its window was captured")
                receipt["observed_alive_ms"] = round((time.monotonic() - started) * 1000)
                receipt["ready_observation_ms"] = round((time.monotonic() - ready_at) * 1000)
                receipt["peak_observed_rss_kib"] = max(sample["memory_kib"]["VmRSS"] for sample in samples)
                receipt["process_high_water_rss_kib"] = max(sample["memory_kib"]["VmHWM"] for sample in samples)
                receipt["gui_startup_passed"] = True
        finally:
            if process is not None:
                receipt["exit_before_cleanup"] = process.poll()
                try:
                    os.killpg(process.pid, signal.SIGTERM)
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid, signal.SIGKILL)
                    process.wait(timeout=5)
                except ProcessLookupError:
                    pass
                receipt["cleanup_exit_code"] = process.returncode
            if server is not None:
                server.shutdown()
                server.server_close()
                thread.join(timeout=5)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("source", "native-source", "binary", "native-library", "frontend", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--timeout-seconds", type=int, default=60)
    parser.add_argument("--observe-seconds", type=int, default=10)
    args = parser.parse_args()
    if not 5 <= args.observe_seconds < args.timeout_seconds <= 120:
        parser.error("Require 5 <= observation < timeout <= 120 seconds")
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    receipt = {"kind": "ocr-linux-desktop-startup", "schema": 1,
               "started_utc": datetime.now(timezone.utc).isoformat(), "passed": False,
               "cli_passed": False, "gui_startup_passed": False,
               "scope": {"binary_execution_required": True, "production_frontend_required": True,
                         "ocr_interactions_qualified": False, "visual_content_qualified": False,
                         "models_downloaded": False, "physical_desktop_qualified": False}}
    try:
        execute(args, output, receipt)
        receipt["passed"] = True
    except Exception as error:
        receipt["error"] = f"{type(error).__name__}: {error}"
    finally:
        receipt["finished_utc"] = datetime.now(timezone.utc).isoformat()
        (output / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({"passed": receipt["passed"], "receipt": str(output / "receipt.json"),
                      "error": receipt.get("error")}))
    return 0 if receipt["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
