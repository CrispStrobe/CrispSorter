/// One indexed chunk on the wire. Sent by the client to `POST /v1/ingest`
/// (singular, today) — the future bulk endpoint
/// `POST /v1/ingest/batch` (PLAN P11 step 4) will accept `Vec<IngestChunk>`.
///
/// `embedding` is a pre-computed dense vector (typically 1024-dim BGE-M3).
/// Its length must equal the server's configured `EMBED_DIMS`; servers
/// reject mismatches with HTTP 422.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct IngestChunk {
    /// Stable document identifier. Explicit identifiers remain authoritative;
    /// ordinary per-file clients can opt into source occurrence resolution.
    pub doc_id: String,
    /// Version 1 identifies an ordinary owner/URI occurrence generated by the
    /// shared identity helper. Requires a complete declared chunk sequence.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_identity_version: Option<u32>,
    /// 0-based index within the document's chunk sequence.
    pub chunk_index: i32,
    /// Total chunks in a complete document replacement, when known.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub chunk_total: Option<i32>,
    /// Inclusive UTF-8 byte offset in the original document text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub chunk_start_char: Option<i32>,
    /// Exclusive UTF-8 byte offset in the original document text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub chunk_end_char: Option<i32>,
    /// Plain-text body of the chunk. Required.
    pub full_text: String,
    /// Optional Markdown rendering of the chunk (preserves headings /
    /// lists / tables for display).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub full_text_md: Option<String>,
    /// Optional list of heading-path strings leading to this chunk.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub headings: Option<Vec<String>>,
    /// Pre-computed dense embedding. Length must match server `EMBED_DIMS`.
    pub embedding: Vec<f32>,

    // ── Document-level metadata (mostly redundant across chunks of one doc;
    //    the server's denormalised storage trades a few KB for fewer joins).
    /// Display title (PDF /Info.Title, DOCX core.title, etc).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub title: Option<String>,
    /// Display author.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub author: Option<String>,
    /// Publication year extracted from metadata.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub year: Option<i32>,
    /// File name including extension.
    pub filename: String,
    /// Lowercase extension without leading dot (`pdf`, `docx`, …).
    pub ext: String,
    /// ISO-639-1 language code (`en`, `de`, …) or empty if unknown.
    pub language: String,
    /// Stable URI for the file's location, e.g. `crisp+local://owner-uuid@machine-uuid/path`.
    pub location_uri: String,
    /// Owner / user identifier — used for multi-tenant filtering.
    pub owner_id: String,
    /// SHA-256 of the source file's bytes, independent of the stable document ID.
    pub source_hash: String,
    /// User-supplied tags. Always serialised, empty `[]` if none.
    #[serde(default)]
    pub tags: Vec<String>,
    /// Source parent directory or URI prefix.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent_dir: Option<String>,
    /// Mounted source volume identity.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub volume_id: Option<String>,
    /// Original source URL.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    /// Stored translated document text, when available.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_translated: Option<String>,
    /// Language of the stored translated text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_translated_lang: Option<String>,
    /// Document review status.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub doc_status: Option<String>,
    /// Audio duration in seconds.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub audio_duration_seconds: Option<f64>,
    /// Camera manufacturer.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image_camera_make: Option<String>,
    /// Camera model.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub image_camera_model: Option<String>,

    /// Typed provenance for an independently indexed member document.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub container_member: Option<ContainerMemberLocator>,
    /// Captured source bytes for the root of one complete member group.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub container_source: Option<ContainerSourceReceipt>,
    /// Explicit extraction coverage retained with roots and nested containers.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub container_coverage: Option<ContainerCoverage>,

}

/// Response for `POST /v1/ingest`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IngestResponse {
    /// Number of chunks accepted (always 1 today; will be `chunks.len()`
    /// once the bulk endpoint lands).
    pub chunk_count: usize,
    /// Server-measured time spent in the LanceDB / Tantivy write path.
    pub write_time_ms: u64,
}

/// Response for `POST /v1/ingest/batch`.
///
/// The server persists the batch to its durable queue and returns
/// immediately; the client polls `/v1/tasks/:id` for completion.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BatchIngestResponse {
    /// Opaque server-generated task identifier.
    pub task_id: String,
    /// Number of tasks currently queued behind or alongside this one.
    pub queue_depth: usize,
    /// Number of chunks accepted into the queued batch.
    pub chunk_count: usize,
}

/// Response for `GET /v1/tasks/:id`.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskStatusResponse {
    /// Echo of the looked-up task identifier.
    pub task_id: String,
    /// `queued` | `processing` | `done` | `failed`
    pub state: String,
    /// Number of chunks originally enqueued in this task.
    pub total_chunks: usize,
    /// Number of chunks written so far. For the initial batch queue this is
    /// `0` until the task succeeds, then `total_chunks`.
    pub completed_chunks: usize,
    /// Current queue depth across all non-terminal tasks.
    pub queue_depth: usize,
    /// Number of attempts already consumed, including the current one when
    /// `state = processing`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub attempt_count: Option<u32>,
    /// Maximum attempts before the task becomes terminally `failed`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_attempts: Option<u32>,
    /// Unix epoch milliseconds when the worker most recently renewed the lease.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_heartbeat_at: Option<i64>,
    /// Unix epoch milliseconds when the current worker lease expires.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lease_expires_at: Option<i64>,
    /// Human-readable error string when `state = "failed"`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

/// Bulk-ingest request body for `POST /v1/ingest/batch` (PLAN P11
/// step 4). Same chunk shape as the singular endpoint; the server
/// coalesces all chunks into one Arrow record-batch + one Tantivy
/// commit, which is materially faster than N individual writes for
/// large ingests.
///
/// On the local side the same shape lets `index_ingest_batch` write N
/// documents in a single LanceDB transaction; the wire format and the
/// in-process struct are identical so the client/server cutover is a
/// trait-impl swap, not a re-encode.
///
/// Server response is `IngestResponse` with `chunk_count = chunks.len()`.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct IngestBatch {
    /// Versioned complete root/member publication. Requires the dedicated
    /// container endpoint; older servers cannot silently accept this payload.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub container_group_version: Option<u32>,
    /// Pre-embedded chunks. Every element is validated against the
    /// server's `EMBED_DIMS` exactly the way the singular endpoint
    /// does; one mismatch rejects the whole batch with HTTP 422 to
    /// keep partial writes off the table.
    #[serde(default)]
    pub chunks: Vec<IngestChunk>,
}

